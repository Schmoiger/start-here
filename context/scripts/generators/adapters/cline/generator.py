from pathlib import Path
from typing import Any
import json

import yaml

from context.scripts.generators.adapters.core.models import CanonicalSkill


def _extract_cline_model_mappings(repo_root: Path) -> str:
    """Extract provider model aliases from context/models.yaml for the Cline runtime.

    Cline is provider-agnostic, so every provider family in the canonical
    tier LUT is listed with its runtime alias for operator reference.
    """
    models_yaml_path = repo_root / "context" / "models.yaml"
    if not models_yaml_path.exists():
        return ""

    try:
        data = yaml.safe_load(models_yaml_path.read_text())
        tiers = data.get("tiers", {})

        mappings: list[str] = []
        for tier_name, tier_data in tiers.items():
            providers = tier_data.get("providers", {})
            for provider_name, provider in providers.items():
                alias = provider.get("runtime_alias", "unknown")
                mappings.append(f"- `{tier_name}` ({provider_name}) -> `{alias}`")

        if mappings:
            return "\n".join(mappings)
    except Exception:
        pass

    return ""


def generate_cline_md(
    context: dict[str, Any], output_dir: Path, dry_run: bool = False
) -> dict[Path, str]:
    """Generates the repository-level CLINE.md runtime entry file."""
    cline_md_path = output_dir / "CLINE.md"

    model_mappings = _extract_cline_model_mappings(output_dir)

    content = (
        "# Cline System Instructions\n\n"
        "**Auto-generated by context/scripts/generators/generate_adapters.py — do not edit manually**\n\n"
        "Please read and strictly adhere to the instructions, standards, and workflows defined in `@AGENTS.md`.\n\n"
        "## Tool Mappings\n"
        "- Use `write_to_file` / `apply_diff` for creating and editing files (the `AGENTS.md` tool names are Gemini-oriented).\n"
        "- Use `execute_command` for executing terminal commands.\n"
        "- Use `read_file` for reading files.\n"
        "- Use `search_files` / `list_files` for finding and searching files.\n"
        "- Use `browser_action` for browser automation.\n\n"
        "## Rules & Skills\n"
        "- Always-on constraints are in `.clinerules/00-core.md` — apply throughout the session.\n"
        "- Procedural skills are in `.cline/skills/` — they load on demand when a task matches a skill's description; consult the **agent-sandbox** skill before running terminal commands.\n\n"
        "## Model Mappings\n"
        "Cline is provider-agnostic; the operator selects the provider for each task tier.\n"
        f"{model_mappings}\n"
    )

    if not dry_run:
        cline_md_path.write_text(content)

    return {cline_md_path: content}


def generate_cline_rules(
    context: dict[str, Any], output_dir: Path, dry_run: bool = False
) -> dict[Path, str]:
    """Generates the always-on .clinerules/00-core.md workspace rule.

    Must NOT carry YAML frontmatter: rules without frontmatter are active
    for every session by Cline's rules semantics.
    """
    rules_path = output_dir / ".clinerules" / "00-core.md"

    content = (
        "# Cline Core Rules (always active)\n\n"
        "**Auto-generated by context/scripts/generators/generate_adapters.py — do not edit manually**\n\n"
        "- Use `yarn` — never `npm` (see `context/standards/tech-standards.md`).\n"
        "- After an apparently failed command, verify true state before retrying: `git -C <root> log --oneline -3`, `git -C <root> status`, `git -C <root> diff --stat`, or read the command's output temp file. Treat \"no result signal\" as unknown, not failed.\n"
        "- Run non-interactive terminal commands that may produce animated output as `CI=1 yarn <command> > /tmp/<name>-out.txt 2>&1`; read the file in a separate step.\n"
        "- Read `@CLINE.md` for tool mappings and `@AGENTS.md` for workflow and agent dispatch before starting a task.\n"
    )

    if not dry_run:
        rules_path.parent.mkdir(parents=True, exist_ok=True)
        rules_path.write_text(content)

    return {rules_path: content}


def generate_cline_skills(
    context: dict[str, Any], output_dir: Path, dry_run: bool = False
) -> dict[Path, str]:
    """Projects canonical skills into Cline .cline/skills/<name>/SKILL.md folders.

    Canonical skills only — agent definitions are not skills and are not
    emitted here (agents are dispatched via @context/agents references).
    Cline triggers a skill from its frontmatter description (max 1024 chars).
    """
    skills: dict[str, CanonicalSkill] = context.get("skills", {})
    skills_dir = output_dir / ".cline" / "skills"

    results: dict[Path, str] = {}

    for skill_name, skill in skills.items():
        skill_dir = skills_dir / skill_name
        skill_path = skill_dir / "SKILL.md"

        description = skill.description
        if len(description) > 1024:
            description = description[:1021] + "..."

        body = skill.body if hasattr(skill, "body") and skill.body else ""

        if body.startswith("# "):
            parts = body.split("\n", 1)
            title_line = parts[0]
            rest = parts[1] if len(parts) > 1 else ""
            content = (
                "---\n"
                f"name: {skill.name}\n"
                f"description: {json.dumps(description, ensure_ascii=False)}\n"
                "---\n\n"
                f"{title_line}\n\n"
                "**Auto-generated by context/scripts/generators/generate_adapters.py — do not edit manually**\n"
                f"{rest}\n"
            )
        else:
            content = (
                "---\n"
                f"name: {skill.name}\n"
                f"description: {json.dumps(description, ensure_ascii=False)}\n"
                "---\n\n"
                f"# {skill.name.replace('-', ' ').title()}\n\n"
                "**Auto-generated by context/scripts/generators/generate_adapters.py — do not edit manually**\n\n"
                f"{body}\n"
            )

        results[skill_path] = content
        if not dry_run:
            skill_dir.mkdir(parents=True, exist_ok=True)
            skill_path.write_text(content)

    return results
